#!/usr/bin/env node
/* Builds src/DesignThix/wwwroot/img/dt-icons.svg (the tool icons of the designer, symbols dt-i-*) from the MatUi icon library of MatDesign
   (../MatDesign/src/MatUi/wwwroot/iconlib/matui-iconlib.svg, Lucide icons, ISC licence). Run: node tools/dt-icons.js [path to matui-iconlib.svg]
   Add a name to NAMES, run the tool, use it as <use href="#dt-i-NAME"> (Ui.ToolIcon in Razor, icon() in the designer scripts). */
'use strict';
const fs = require('fs');
const path = require('path');

const NAMES = [
  'align-start-vertical', 'align-center-vertical', 'align-end-vertical', 'align-start-horizontal', 'align-center-horizontal', 'align-end-horizontal',
  'align-horizontal-space-between', 'align-vertical-space-between', 'bring-to-front', 'send-to-back', 'arrow-up-to-line', 'arrow-down-to-line',
  'square', 'circle', 'ellipse', 'minus', 'rotate-cw', 'lock-open', 'zoom-in', 'zoom-out', 'maximize', 'scan', 'undo-2', 'redo-2', 'grid-3x3', 'magnet',
  'bold', 'italic', 'case-upper', 'text-align-start', 'text-align-center', 'text-align-end', 'panel-left', 'panel-right', 'sliders-horizontal',
  'images', 'image-plus', 'braces', 'variable', 'text-cursor-input', 'heading-1', 'cloud-off', 'cloud-check', 'hand', 'move', 'ruler',
  'square-round-corner', 'scaling', 'text-wrap', 'radius', 'gallery-horizontal-end', 'a-large-small', 'type', 'image', 'layers', 'eye', 'eye-off',
  'lock', 'trash', 'copy', 'clipboard-paste', 'plus', 'x', 'chevron-left', 'chevron-right', 'chevron-down', 'chevron-up', 'arrow-left', 'arrow-up', 'arrow-down',
  'save', 'printer', 'check', 'pencil', 'grip-vertical', 'rectangle-horizontal', 'space', 'shrink', 'expand', 'move-vertical', 'move-horizontal', 'list', 'database',
  'layout-template', 'shapes', 'cloud-upload', 'group', 'ungroup', 'download', 'ellipsis', 'ellipsis-vertical', 'blend', 'droplet', 'underline', 'strikethrough', 'layers-2', 'frame', 'qr-code', 'barcode', 'triangle', 'hexagon', 'star', 'heart', 'pentagon', 'diamond', 'message-square', 'file-stack', 'file-plus', 'copy-plus', 'clock', 'keyboard', 'replace', 'crop', 'scissors', 'link-2', 'unlink', 'paint-bucket', 'sticker', 'case-sensitive', 'grip-horizontal', 'square-plus', 'image-down', 'wand-sparkles', 'rotate-ccw', 'mouse-pointer-2', 'brush', 'arrow-left-right', 'arrow-up-down', 'chevrons-up-down', 'file-down', 'file-image', 'lock-keyhole', 'panel-bottom', 'layout-grid', 'arrow-right', 'square-pen', 'at-sign', 'list-ordered', 'panel-left-close', 'panel-left-open', 'circle-plus', 'circle-minus', 'folder-open', 'hash', 'badge-check', 'message-circle', 'list-minus', 'file-clock', 'text-quote', 'circle-question-mark', 'palette',
  'search', 'baseline', 'minimize-2', 'monitor', 'smartphone', 'info', 'triangle-alert', 'pipette', 'paintbrush', 'circle-dashed', 'square-dashed', 'tags',
  // the file browser (P2)
  'folder-plus', 'folder-input', 'share-2', 'star-off', 'inbox', 'file-up', 'table-2', 'users-round', 'folder-closed', 'check-check', 'search-x',
  // sharing (P3)
  'user-plus', 'globe', 'link', 'users', 'user', 'circle-user-round', 'mail-plus',
];

const source = process.argv[2] || path.join(__dirname, '..', '..', 'MatDesign', 'src', 'MatUi', 'wwwroot', 'iconlib', 'matui-iconlib.svg');
const text = fs.readFileSync(source, 'utf8');
const symbols = [];
const missing = [];
for (const name of NAMES) {
  const start = text.indexOf('<symbol id="mat-il-' + name + '"');
  const end = start < 0 ? -1 : text.indexOf('</symbol>', start);
  if (start < 0 || end < 0) { missing.push(name); continue; }
  symbols.push('  ' + text.slice(start, end + '</symbol>'.length).replace('id="mat-il-' + name + '"', 'id="dt-i-' + name + '"'));
}
if (missing.length) { console.error('Not in the icon library: ' + missing.join(', ')); process.exitCode = 1; }

const out = [
  '<svg xmlns="http://www.w3.org/2000/svg" class="mat-sprite" width="0" height="0" aria-hidden="true" focusable="false">',
  '  <!-- DesignThix tool icons (the designer). Generated by tools/dt-icons.js from the MatUi icon library of MatDesign.',
  '       Lucide (https://lucide.dev), ISC License, Copyright (c) 2026 Lucide Icons and Contributors. Permission to use, copy, modify, and/or distribute',
  '       this software for any purpose with or without fee is hereby granted, provided that the above copyright notice and this permission notice appear',
  '       in all copies. THE SOFTWARE IS PROVIDED "AS IS" WITHOUT WARRANTY OF ANY KIND. Parts derive from Feather (MIT, Copyright (c) 2013-2017 Cole Bemis). -->',
  ...symbols,
  '</svg>',
  '',
].join('\n');
const target = path.join(__dirname, '..', 'src', 'DesignThix', 'wwwroot', 'img', 'dt-icons.svg');
fs.writeFileSync(target, out);
console.log('Wrote ' + symbols.length + ' icons to ' + target);
