#!/usr/bin/env node
/* Measures the bundled fonts for the lint of the design assistant (Logic/AiTextMetrics.cs): the average advance of a lower case letter, a capital, a digit, a space and a punctuation mark in em,
   regular and bold, per family. The server has no font engine; with these numbers it estimates how wide a text really is, so "these two texts overlap" and "this text does not fit its box" are
   judged on the ink and not on the boxes. Needs no running app (Playwright + the installed Edge, the fonts come straight from wwwroot/fonts).

     node tools/ai-font-metrics.js            prints the C# table
     node tools/ai-font-metrics.js --write    rewrites src/DesignThix/Logic/AiFontMetrics.cs

   Run it again when a font is added (the test FontGuideTests fails for a family without a row). */
'use strict';
const fs = require('fs');
const http = require('http');
const path = require('path');

const root = path.join(__dirname, '..');
const wwwroot = path.join(root, 'src', 'DesignThix', 'wwwroot');
const { chromium } = require(path.join(root, 'tests', 'e2e', 'node_modules', 'playwright'));
const fonts = JSON.parse(fs.readFileSync(path.join(wwwroot, 'fonts', 'fonts.json'), 'utf8'));

const SAMPLES = {
  lower: 'abcdefghijklmnopqrstuvwxyzäöüßabeeeeinnrrsstt',   // letters in about the frequency of German
  upper: 'ABCDEFGHIJKLMNOPQRSTUVWXYZÄÖÜ',
  digit: '0123456789',
  space: ' ',
  punct: '.,;:!?-–()„“/&%€',
};

const types = { '.json': 'application/json', '.ttf': 'font/ttf', '.woff2': 'font/woff2', '.woff': 'font/woff', '.otf': 'font/otf', '.html': 'text/html' };
const server = http.createServer((req, res) => {
  const url = new URL(req.url, 'http://localhost');
  if (url.pathname === '/') { res.writeHead(200, { 'Content-Type': 'text/html' }); return res.end('<!doctype html><meta charset="utf-8"><body>'); }
  const file = path.join(wwwroot, path.normalize(decodeURIComponent(url.pathname)).replace(/^([\\/])+/, ''));
  if (!file.startsWith(wwwroot) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'Content-Type': types[path.extname(file)] || 'application/octet-stream' });
  res.end(fs.readFileSync(file));
});

(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try { browser = await chromium.launch({ channel: 'msedge' }); } catch (e) { browser = await chromium.launch(); }
  const page = await (await browser.newContext()).newPage();
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  const result = await page.evaluate(async ({ fonts: list, samples }) => {
    const out = {};
    const families = [...new Set(list.map(f => f.family))];
    for (const family of families) {
      const faces = list.filter(f => f.family === family && f.style === 'normal');
      for (const f of faces) {
        const ff = new FontFace(family, `url(/fonts/${f.file})`, { weight: String(f.weight), style: f.style });
        await ff.load();
        document.fonts.add(ff);
      }
      const ctx = document.createElement('canvas').getContext('2d');
      const row = {};
      for (const [name, weight] of [['regular', 400], ['bold', 700]]) {
        row[name] = {};
        for (const [cls, text] of Object.entries(samples)) {
          ctx.font = `${weight} 1000px "${family}"`;
          row[name][cls] = Math.round(ctx.measureText(text).width / text.length) / 1000;
        }
      }
      out[family] = row;
    }
    return out;
  }, { fonts, samples: SAMPLES });
  await browser.close();
  server.close();

  const f = n => n.toFixed(3).replace(/0+$/, '').replace(/\.$/, '.0');
  const lines = Object.entries(result).sort((a, b) => a[0].localeCompare(b[0])).map(([family, r]) =>
    `        ["${family}"] = new(${['regular', 'bold'].map(w => `new(${['lower', 'upper', 'digit', 'space', 'punct'].map(c => f(r[w][c])).join(', ')})`).join(', ')}),`);
  const cs = `namespace DesignThix.Logic;

// GENERATED by tools/ai-font-metrics.js from the bundled fonts: do not edit by hand (run the script again when a font is added).
public static partial class AiFontMetrics
{
    /// <summary>Per family: the average advance in em of lower case letters, capitals, digits, the space and punctuation, regular (400) and bold (700).</summary>
    private static readonly Dictionary<string, FamilyMetrics> Table = new(StringComparer.OrdinalIgnoreCase)
    {
${lines.join('\n')}
    };
}
`;
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(root, 'src', 'DesignThix', 'Logic', 'AiFontMetrics.Generated.cs'), cs);
    console.log('written: src/DesignThix/Logic/AiFontMetrics.Generated.cs (' + lines.length + ' families)');
  } else {
    console.log(cs);
  }
})().catch(e => { console.error(e); process.exit(1); });
