'use strict';
/* Helpers of batch T3b (numbers 400-499). A family lives in one file _f-<family>.js that exports an ARRAY of template modules; _t3b-gen.js writes the thin numbered
   files 4NN-<slug>.js that the build picks up (a module file exports ONE template). `family(common, [variantObject, ...])` merges the shared metadata. */
const fs = require('fs');
const path = require('path');

function family(common, variants) {
  return variants.map((v, i) => Object.assign({}, common, v, { no: v.no || (common.no + i) }, { tags: [...new Set([...(common.tags || []), ...(v.tags || [])])] }));
}

/** Writes tools/templates/<no>-<slug>.js for every _f-*.js (idempotent). */
function generate() {
  const dir = __dirname;
  const written = [];
  for (const f of fs.readdirSync(dir).filter(x => /^_t3b_f-.*\.js$/.test(x))) {
    const list = require(path.join(dir, f));
    for (const t of list) {
      const name = `${t.no}-${t.slug}.js`;
      const body = `'use strict';\n// Generated by _t3b-gen.js: the template lives in ${f}\nmodule.exports = require('./${f}').find(t => t.slug === '${t.slug}');\n`;
      const file = path.join(dir, name);
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== body) fs.writeFileSync(file, body);
      written.push(name);
    }
  }
  // remove stubs of templates that were renamed or dropped
  for (const f of fs.readdirSync(dir).filter(x => /^4\d\d-.*\.js$/.test(x))) if (!written.includes(f)) fs.unlinkSync(path.join(dir, f));
  return written;
}

const { rect } = require('./dsl');
/** fade(name, x, y, w, h, color, maxOpacity, dir): a soft shadow made of stacked strips (the engine has no transparent gradient stops). dir 'up' = dense at the bottom, 'down' = dense at the top. */
function fade(name, x, y, w, h, color, maxOpacity = 0.8, dir = 'up', steps = 16) {
  const out = [];
  const sh = h / steps;
  for (let i = 0; i < steps; i++) {
    const t = (i + 1) / steps;
    const o = maxOpacity * (dir === 'up' ? t : 1 - i / steps) * (dir === 'up' ? 1 : 1);
    out.push(rect(name + ' ' + (i + 1), x, y + i * sh, w, sh + 0.6, color, { opacity: Math.round(Math.min(1, dir === 'up' ? maxOpacity * t * t : maxOpacity * (1 - i / steps) * (1 - i / steps)) * 1000) / 1000, locked: true }));
  }
  return out;
}

module.exports = { family, generate, fade };
